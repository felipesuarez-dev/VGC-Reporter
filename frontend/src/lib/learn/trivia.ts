import type { LearnLang } from "./types";

interface TriviaText {
  statement: string;
  answer: boolean;
  explanation: string;
}

export interface TriviaSeed {
  id: string;
  text: Record<LearnLang, TriviaText>;
}

function t(
  id: string,
  es: [string, boolean, string],
  en: [string, boolean, string],
  fr: [string, boolean, string],
  it: [string, boolean, string],
  pt: [string, boolean, string],
): TriviaSeed {
  const pack = (value: [string, boolean, string]): TriviaText => ({
    statement: value[0],
    answer: value[1],
    explanation: value[2],
  });
  return {
    id,
    text: {
      es: pack(es),
      en: pack(en),
      fr: pack(fr),
      it: pack(it),
      pt: pack(pt),
    },
  };
}

